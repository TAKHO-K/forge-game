-- 캐릭터 레벨 곡선(13-2 도입, 25-1 재설계). 스탯 배율 쪽(statBonusPerLevel·weaponMultGrowthRate)은
-- 13-2/20.10 그대로이고, 경험치 요구치 쪽은 25-1에서 "목표 마릿수 곡선에서 역산"하는 구조로
-- 바뀌었다 - 실제 계산은 전부 shared/CharacterLevel.lua가 한다.
--
-- 25-1 이전 구조(참고용 - SaveSystem.migrate v22가 옛 세이브를 옮길 때 리터럴로 보존한다):
--   1~25 손튜닝 누적표(weaponLevelExp) + 26+ 지수식 + 회차 상수 배수(firstRunExpMultiplier
--   6.17 / rebirthCount+1). 회차마다 곡선 "모양"이 없고 상수 하나로 일괄 나누는 형태였다.

return {
	-- 레벨당 스탯 보너스 계수(1~statLinearMaxLevel 구간, 선형). data/balance.js
	-- weaponExpAttackBonusPerLevel과 data/items.js ITEM_LEVEL_STAT_BONUS_PER_LEVEL이 원래 같은
	-- 값(0.06)이었던 것을 그대로 재사용한다 - 무기 공격력·아이템 스탯이 레벨25에서 나란히
	-- 2.44배로 정점을 찍는 대칭(웹 설계 의도, data/items.js 75-78행 주석)을 그대로 가져온다.
	statBonusPerLevel = 0.06,

	-- 선형 스탯 구간의 끝 레벨. 25-1 전엔 weaponLevelExp 표 길이(25)에서 파생됐는데, 표가
	-- 없어지면서 명시적인 값이 됐다 - 값 자체는 바뀌지 않았다(무기 배율·아이템 계수 함수가
	-- 이 레벨을 경계로 선형→지수로 넘어간다, CharacterLevel.getWeaponExpMultiplier 등).
	statLinearMaxLevel = 25,

	-- 26+ 구간 무기 공격력 배율 성장률(g). PRD 20.10 확정값 - 몬스터 HP 성장률
	-- k=1.155(InfiniteStageConfig.growthRate)보다 살짝 낮게 잡아 스테이지가 오를수록
	-- 아주 조금씩 어려워지도록 설계됐다(20.10 "왜 레벨당 +6%를 무한 구간에 그대로 못 쓰는가").
	-- P2.5a C2: 1.15 → 1.02(= k). g ≤ k 조건(사용자 결정) 안에서, 주 구간은 g = k로 두어 "레벨 1 = 스테이지 1"만큼 강해지고(레벨업 간격이 시간에
	-- 따라 늘지 않는다 - C3 "12시간 이후 ≤ 15분"), 천장은 아래 weaponGrowthLate(fromLevel부터 rate < k)가 만든다(구간별 g). 값 근거 = docs/phase/P25a-log.md.
	weaponMultGrowthRate = 1.02,
	-- 천장(구간별 g): 레벨 20,000부터 1.01(= k의 절반 몫 - 레벨 한 칸이 스테이지 0.5칸). 진행은 방어구 사다리(가방 점검마다 +4 ~ 6스테이지)가 정해 g와 무관하게
	-- 빠르므로(상위 1% 약 60스테이지/시간), 천장이 없으면 상위 1%가 2,190시간에 13만 스테이지(1e250 초과)까지 간다. fromLevel 20,000 = 설계 최대(약 21,000)의 수치가
	-- 1e190 안쪽(1e250까지 60자리 여유) · 일반 프로필이 천장에 닿는 때 ≈ 누적 1,400시간(하루 3시간 약 15개월). 값 근거 = docs/phase/P25a-log.md.
	weaponGrowthLate = { fromLevel = 20000, rate = 1.01 },

	-- P2.5a C10 · E: 레벨 → 스테이지 척도. 앵커 장비(일반 3부위 itemLevel = 레벨, 무기 등급 0 · +0)로 tier1을 2.5초에 잡는 스테이지 = 레벨 + 이 값
	-- (BalanceSim.solveKillOffset - k = 1.02에서 +167.0, P25a(가)가 대조한다). 옛 k에서는 0이라 "레벨 L = 스테이지 L"이었다 - 새 k에서는 무기 계수(25 뒤 k^(L−25))와
	-- 몬스터 HP(k^(S−1))의 접합 배율이 달라 앵커 장비만으로 167스테이지 위를 잡는다. 이 척도를 두 곳이 같이 쓴다: 환생 지급 보석 itemLevel(PlayerProfile.rebirth -
	-- 결정 9 "환생 당시 캐릭터 레벨") · 경험치 기준 스테이지(CharacterLevel.getMonsterExpAtLevel - 레벨 L → L+1 필요 경험치 = K(L) × 스테이지 L + 이 값의 tier1 경험치).
	levelStageOffset = 167,

	-- 몬스터 처치 경험치 계수(17-1). MonsterData.lua가 각 tier의 expReward를
	-- `hp × monsterExpCoefficient`로 계산하는 데 쓴다 - "몬스터 경험치는 그 몬스터의 최대
	-- HP에 비례한다"는 설계(17-1 [0]).
	-- 25-1부터 이 값은 "레벨당 처치 수"에 영향을 주지 않는다 - 경험치 요구치가 실제 몬스터
	-- 경험치(이 계수 포함)에서 역산되므로, 계수를 바꾸면 화면에 보이는 경험치 숫자의 크기만
	-- 바뀌고 마릿수는 아래 killTargetAnchors가 그대로 고정한다. 17-1 시절의 "0.025는 레벨당
	-- 25마리가 되도록 역산한 값"이라는 의미는 이제 없다(값은 그대로 둔다 - 경험치 숫자 눈금이
	-- 바뀌면 기존 세이브 이관에 이유 없는 잡음이 생긴다).
	monsterExpCoefficient = 0.025,

	-- 25-1: 레벨업 1회에 필요한 몬스터 처치 수(목표 마릿수)의 앵커. 레벨 L→L+1에 필요한 처치 수
	-- K(L)을 이 점들 사이 선형 보간으로 정의하고(CharacterLevel.getTargetKills), 마지막 앵커
	-- 이후는 그 값으로 고정한다. 경험치 요구치는 K(L)에서 역산한다:
	--   레벨 L→L+1 필요 경험치 = round(K(L) × E(L)),  E(L) = tier1 몬스터가 스테이지 L에서 주는 경험치
	-- 즉 "자기 레벨에 맞는 스테이지(rec(L)=L, 20.44 앵커)에서 tier1을 사냥할 때" K(L)마리다.
	-- 다른 구역(tier2+)은 경험치도 HP도 r^p배라 시간 기준으로는 같고, 마릿수 기준으로는 더 적다.
	--
	-- 값의 근거(25-1 지시 표): 도입(레벨1~) 7마리 미만 → 1회차 끝(25) 10 → 2회차 끝(50) 15
	-- → 3회차 끝(75) 20 → 5회차 끝(125) 25. 레벨1의 5는 "7마리 미만" 안에서 고른 값이다(임의
	-- 결정 - 레벨 ~11에서 7마리에 닿아 도입 구간이 약 10레벨 = 처치 60마리 = 2.5분 안팎).
	-- 선형 보간을 고른 이유: 인접 구간 기울기(0.208/0.2/0.2/0.1 마리/레벨)의 차이가 0.1 이하라
	-- 매끄러운 보간(단조 3차 등)을 써도 체감 차이가 없고, 선형은 표를 손으로 검산할 수 있다.
	-- 값 자체는 경계에서 연속이다(계단 없음) - 튀는 것은 기울기뿐이고 그건 눈에 안 보인다.
	--
	-- "625마리 항등식"(20.38 [1], 25마리×25레벨)의 재정의: 레벨당 25마리는 마지막 앵커(레벨125,
	-- 5회차 끝)에서 처음 도달하는 값이고 그 이후 구간에서만 성립한다. 1~4회차는 초반 가속을
	-- 위해 의도적으로 그보다 낮다(회차별 실제 합계는 PRD 20.66 표 참고).
	-- P2.5c 결정 3: 환생 필요 레벨이 25 · 50 · 75 · 100 · 125로 고정되면서, 레벨은 방어구 사다리가 정하는 사냥 스테이지를 일정한 간격으로 따라가므로
	-- (P2.5c 로그) 환생 시각은 "그 회차 끝 레벨의 요구 경험치"가 정한다. 그래서 회차 끝(50 · 75 · 100 · 125)으로 갈수록 목표 마릿수를 키워 일반 프로필 환생
	-- 1 · 2 · 5회차를 30 ~ 60분 · 약 2시간 · 약 12시간에 맞췄다(환생 경험치 배율 rebirth.expMultipliers와 함께 - 값 = 하네스 격자, docs/phase/P25c-log.md).
	-- 마지막 앵커(125)는 Option.levelFactor의 동결 레벨로도 쓰인다(그 모듈 주석) - 125를 마지막으로 둔다.
	killTargetAnchors = {
		{ level = 1, kills = 5 },
		{ level = 25, kills = 15 },
		{ level = 50, kills = 60 },
		{ level = 75, kills = 350 },
		{ level = 100, kills = 2500 },
		{ level = 125, kills = 20000 },
	},
	-- P2.5c 결정 3: 마지막 앵커 뒤(126 ~ - 5회 환생 뒤에만 닿는다)의 목표 마릿수. 환생 구간 곡선(위)과 따로 둔다 - 5회 뒤 레벨이 사냥 스테이지를 따라가는
	-- 간격이 옛 곡선(25마리 · 배율 1)과 같도록 = 25 × 5회 뒤 경험치 배율(expMultipliers[6]).
	killTargetAfterAnchors = 25 * 6,

	-- P2 B(초반 가속, 결정 2B): i번째 환생에 필요한 캐릭터 레벨(index = 지금까지의 환생 횟수 + 1). P2 전에는 25 × i 고정식(25 · 50 · 75 · 100 · 125)이
	-- PlayerProfile.rebirth · 환생 UI에 박혀 있었다. 1 · 2회차는 그대로 두고 3 ~ 5회차만 낮췄다 - 목표 "일반 프로필 누적 약 12시간에 환생 5회차"
