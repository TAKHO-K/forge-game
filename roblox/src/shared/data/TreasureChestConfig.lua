-- 로블록스 강화는 골드만 쓰고 강화권 개념이 없어(RareMonsterConfig.lua 재료 몬스터 주석과
-- 같은 이유) 재사용할 보상 축이 없다. 그래서 보상은 **골드(재화)**만 준다 - 장비 등급
-- 체계를 건드리지 않는 축(지시 - "보물상자가 태초를 주면 안 된다"). 외형·칭호 축은
