	-- 등장 확률(스폰마다 판정, 잡몹 슬롯 리스폰 때마다 다시 굴린다). 반짝이(0.5%)의 1/5 -
	-- 반짝이는 "발견하면 나 혼자 잡는" 사건이고 상자는 "서버 전체가 모이는" 사건이라
	-- 더 드물어야 한다. 서버에서 초당 약 1마리가 죽는 활동량(3명이 3초에 1마리씩)이면
