-- 한 번이라도 때린 모든 플레이어가 각자 독립적으로 보상을 받는다 - 경쟁이 아니라
-- "모여들게" 만드는 장치(19-4의 기여 임계값 지급과 같은 철학 - 남이 오는 게 나에게
-- 손해가 아니어야 한다).
--
