	-- 잡몹 골드와 같은 InfiniteStage 배율, 나눠 갖지 않는다). 30마리 ≈ 2~3분 파밍 분량.
	-- 경제 영향: 스폰 0.1% × 30마리분 = 잡몹 골드 수입의 약 +3%(모든 사람이 항상 참여해도).
	goldKillEquivalent = 30,

	-- 외형 - 기본 파트만(아트 동결, 20.27). 잡몹 몸통(2.4×3×1.2)보다 확실히 큰 상자 +
	-- 하늘로 뻗는 빛기둥(멀리서도 "저기 있다"가 되게 - 반짝이 이펙트 레이어와 같은 방식).
	sizeStuds = Vector3.new(6, 4.5, 4.5),
	bodyColor = Color3.fromRGB(120, 72, 30), -- 나무 상자
	trimColor = Color3.fromRGB(255, 200, 60), -- 금테
	glowRangeStuds = 60,
	glowBrightness = 4,
	pillarHeightStuds = 80,
	pillarWidthStuds = 4,
