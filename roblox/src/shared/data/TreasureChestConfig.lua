	-- 플레이어당 유효 피격 간격(초) - 이 설계의 핵심. 없으면 한 명이 0.28초 쿨다운 평타로
	-- 4초 만에 혼자 깨서 "모두가 받는다"가 무의미해진다. 1초면 혼자서는 15타 사이 14간격 =
	-- 최소 14초가 걸리고, 그동안 다른 사람이 달려올 수 있다.
	hitIntervalSeconds = 1,

	-- 못 깨면 사라지는 시간(초). 근거: 가장 먼 구역에서 달려오는 시간 - 슈퍼그리드 대각
	-- (160 × 2 × √2 ≈ 452stud) ÷ 16stud/s ≈ 28초 + 알림을 읽는 반응 ~5초 + 도착 후 혼자
	-- 깨는 최소 14초 ≈ 47초. 그 두 배 가까운 90초를 두어 "알림을 보고 출발하면 늦지
	-- 않는다"를 보장하되, 아무도 안 오는 상자가 스폰 슬롯(리스폰 5초)을 오래 막지 않게 한다.
